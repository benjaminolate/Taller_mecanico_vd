-- Correlativo de las órdenes ("ORD-001", "ORD-002", ...)
CREATE SEQUENCE orden_correlativo_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE clientes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(255) NOT NULL,
    telefono          VARCHAR(255),
    rut               VARCHAR(12) UNIQUE,
    relacion_vehiculo VARCHAR(255)
);

CREATE TABLE vehiculos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente       VARCHAR(10)  NOT NULL UNIQUE,
    marca         VARCHAR(255) NOT NULL,
    modelo        VARCHAR(255) NOT NULL,
    anio          INTEGER,
    tipo_vehiculo VARCHAR(255)
);

CREATE TABLE mecanicos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(255) NOT NULL,
    rut           VARCHAR(12) UNIQUE,
    estado_activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE catalogo_trabajos (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tarea           VARCHAR(255) NOT NULL,
    costo_estimado_defecto NUMERIC(10, 2)
);

CREATE TABLE ordenes_ingreso (
    id           VARCHAR(20)  PRIMARY KEY,
    fecha        TIMESTAMP(6) NOT NULL,
    tipo_ingreso VARCHAR(255) NOT NULL,
    estado       VARCHAR(255) NOT NULL,
    cliente_id   BIGINT NOT NULL REFERENCES clientes (id),
    vehiculo_id  BIGINT REFERENCES vehiculos (id)
);
CREATE INDEX idx_ordenes_fecha    ON ordenes_ingreso (fecha);
CREATE INDEX idx_ordenes_cliente  ON ordenes_ingreso (cliente_id);
CREATE INDEX idx_ordenes_vehiculo ON ordenes_ingreso (vehiculo_id);

CREATE TABLE estados_vehiculo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id          VARCHAR(20) NOT NULL UNIQUE REFERENCES ordenes_ingreso (id) ON DELETE CASCADE,
    rayones           BOOLEAN,
    golpes            BOOLEAN,
    obs_carroceria    TEXT,
    nivel_combustible INTEGER,
    nivel_aceite      BOOLEAN,
    nivel_agua        BOOLEAN,
    neumaticos_ok     BOOLEAN,
    obs_neumaticos    TEXT,
    obs_generales     TEXT
);

CREATE TABLE estados_cremallera (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id         VARCHAR(20) NOT NULL UNIQUE REFERENCES ordenes_ingreso (id) ON DELETE CASCADE,
    dientes_daniados BOOLEAN,
    fugas_aceite     BOOLEAN,
    juego_excesivo   BOOLEAN,
    bujes_gastados   BOOLEAN,
    marca_cremallera VARCHAR(255),
    es_original      BOOLEAN,
    obs_cremallera   TEXT
);

CREATE TABLE trabajos_realizados (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id         VARCHAR(20) NOT NULL REFERENCES ordenes_ingreso (id) ON DELETE CASCADE,
    descripcion      TEXT NOT NULL,
    categoria        VARCHAR(255) NOT NULL,
    mecanico_id      BIGINT REFERENCES mecanicos (id),
    costo_estimado   NUMERIC(10, 2),
    observaciones    TEXT,
    completado       BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_registro   TIMESTAMP(6) NOT NULL,
    fecha_completado TIMESTAMP(6)
);
CREATE INDEX idx_trabajos_orden    ON trabajos_realizados (orden_id);
CREATE INDEX idx_trabajos_mecanico ON trabajos_realizados (mecanico_id);
