-- ============================================================
-- V5: firmas del cliente en la tablet, al recibir y al retirar.
-- Una firma no se edita: si hay un error se anula y se registra otra.
-- firmada = false significa que se eligió "Continuar sin firma".
-- ============================================================
CREATE TABLE firmas_orden (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id         VARCHAR(20)  NOT NULL REFERENCES ordenes_ingreso (id) ON DELETE CASCADE,
    momento          VARCHAR(20)  NOT NULL,
    firmada          BOOLEAN      NOT NULL,
    imagen_png       BYTEA,
    nombre_firmante  VARCHAR(255),
    rut_firmante     VARCHAR(12),
    anulada          BOOLEAN      NOT NULL DEFAULT FALSE,
    anulada_en       TIMESTAMP(6),
    creado_por       VARCHAR(30),
    modificado_por   VARCHAR(30),
    creado_en        TIMESTAMP(6),
    modificado_en    TIMESTAMP(6)
);
CREATE INDEX idx_firmas_orden ON firmas_orden (orden_id);
-- Solo una firma vigente (no anulada) por orden y momento: lo controla
-- FirmaService (H2 no admite índices únicos parciales).
CREATE INDEX idx_firmas_orden_momento ON firmas_orden (orden_id, momento);
